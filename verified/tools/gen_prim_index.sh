# Generates verified/core/src/prims/index.rs (the core module's primitive
# indices and arities) from src/primitive.h. The layout check
# (verified/layout_check.cc) compares the generated table with MODULE_CORE.
#
# Usage: verified/tools/gen_prim_index.sh > verified/core/src/prims/index.rs

set -eu

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

# The (name, arity) pairs of MODULE_CORE, one per line.
PRIMS="$(awk '/^#define MODULE_CORE\(PRIMITIVE\)/ { on = 1; next }
             on && /^$/ { exit }
             on { while (match($0, /PRIMITIVE\([a-z0-9_]+, *[0-9]+\)/)) {
                    s = substr($0, RSTART + 10, RLENGTH - 11); sub(/, */, " ", s); print s
                    $0 = substr($0, RSTART + RLENGTH) } }' "$ROOT/src/primitive.h")"

cat <<'EOF'
// Copyright (C) 2026 Toit contributors.
//
// This library is free software; you can redistribute it and/or
// modify it under the terms of the GNU Lesser General Public
// License as published by the Free Software Foundation; version
// 2.1 only.
//
// This library is distributed in the hope that it will be useful,
// but WITHOUT ANY WARRANTY; without even the implied warranty of
// MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the GNU
// Lesser General Public License for more details.
//
// The license can be found in the file `LICENSE` in the top level
// directory of this repository.

//! The core module's primitive indices and arities (`MODULE_CORE` of
//! src/primitive.h). Generated by verified/tools/gen_prim_index.sh; the
//! layout check compares `TABLE` with the C++ table.

use vstd::prelude::*;

verus! {

EOF
echo "$PRIMS" | awk '{ printf "pub const %s: usize = %d;\n", toupper($1), NR - 1 }'
echo
echo "pub const COUNT: usize = $(echo "$PRIMS" | wc -l);"
echo
echo "} // verus!"
echo
echo "/// (name, index, arity) for the layout check."
echo "pub const TABLE: &[(&[u8], usize, usize)] = &["
echo "$PRIMS" | awk '{ printf "    (b\"%s\\0\", %d, %s),\n", $1, NR - 1, $2 }'
echo "];"
