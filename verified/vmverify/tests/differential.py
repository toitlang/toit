"""Differential test of the trusted conversion from VM memory (from_vm.rs).

For every program of the suite (verified/spec/tests/verify_suite.py's list:
run_suite.py's discovery plus verified/spec/tests/toit), compiled in format 2:

  * the VM path: `toit.run --verify --emit-canonical=F snapshot` loads the
    snapshot as the VM does, decodes the method table, fills the tables the
    core executes and builds the abstract program from that memory;
  * the dump path: tools/spec_dump.toit writes the dump, the reference
    loader (toit_spec::interp::loader) reads it (toit_vmverify_canonical).

Both write the canonical form (canonical.rs); they must be identical. A
mismatch keeps both files (and a diff) under --out.

Usage: differential.py [--jobs N] [--filter S] [--out DIR] [--results FILE]
"""

import argparse
import concurrent.futures
import difflib
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(CRATE))
sys.path.insert(0, os.path.join(REPO, "verified/spec/tests"))
import run_suite  # noqa: E402
import verify_suite  # noqa: E402

TOIT_RUN = os.path.join(os.path.dirname(os.path.dirname(run_suite.TOIT)), "lib/toit/bin/toit.run")
CANONICAL = os.path.join(CRATE, "target/release/toit_vmverify_canonical")


def one(src, opts):
  dump, err = verify_suite.compile_and_dump(src, opts.out, opts.dumper)
  if dump is None:
    return src, err, ""
  snapshot = dump[:-len(".dump")] + ".snapshot"
  from_dump = dump + ".canonical-dump"
  from_vm = dump + ".canonical-vm"
  p = subprocess.run([CANONICAL, dump, from_dump], capture_output=True)
  if p.returncode != 0:
    return src, "dump-load-error", p.stderr.decode("utf-8", "replace")
  p = subprocess.run([TOIT_RUN, "--verify", "--emit-canonical=" + from_vm, snapshot], capture_output=True)
  if p.returncode != 0:
    return src, "vm-error", p.stderr.decode("utf-8", "replace")
  a = open(from_dump).read()
  b = open(from_vm).read()
  if a == b:
    os.remove(from_dump)
    os.remove(from_vm)
    return src, "equal", "%d bytes" % len(a)
  diff = "".join(difflib.unified_diff(a.splitlines(True), b.splitlines(True), "dump", "vm", n=1))
  with open(dump + ".canonical-diff", "w") as f:
    f.write(diff)
  return src, "different", diff[:2000]


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--jobs", type=int, default=os.cpu_count())
  ap.add_argument("--filter", action="append")
  ap.add_argument("--out", default=os.path.join(CRATE, "target/differential"))
  ap.add_argument("--results", help="write one line per program: status program")
  opts = ap.parse_args()
  os.makedirs(opts.out, exist_ok=True)
  subprocess.run(["cargo", "build", "--release", "--quiet", "--bin", "toit_vmverify_canonical"], cwd=CRATE, check=True)
  opts.dumper = os.path.join(opts.out, "spec_dump.snapshot")
  if not os.path.exists(opts.dumper):
    subprocess.run([run_suite.TOIT, "compile", "--snapshot", "-o", opts.dumper,
                    os.path.join(REPO, "tools/spec_dump.toit")], check=True)
  files = [os.path.join(REPO, f) for f in run_suite.discover(opts.filter)]
  files += sorted(os.path.join(REPO, "verified/spec/tests/toit", f)
                  for f in os.listdir(os.path.join(REPO, "verified/spec/tests/toit")) if f.endswith(".toit"))
  if opts.filter:
    files = [f for f in files if any(x in f for x in opts.filter)]
  results = []
  with concurrent.futures.ThreadPoolExecutor(max_workers=opts.jobs) as ex:
    for r in ex.map(lambda f: one(f, opts), files):
      results.append(r)
      if r[1] != "equal":
        print("%s %s" % (r[1], os.path.relpath(r[0], REPO)))
        for line in r[2].splitlines()[:12]:
          print("    " + line)
  counts = {}
  for _, status, _ in results:
    counts[status] = counts.get(status, 0) + 1
  print("programs: %d; %s" % (len(results), ", ".join("%s %d" % kv for kv in sorted(counts.items()))))
  if opts.results:
    with open(opts.results, "w") as f:
      f.write("# Generated by verified/vmverify/tests/differential.py: status, program.\n")
      for src, status, _ in sorted(results):
        f.write("%s %s\n" % (status, os.path.relpath(src, REPO)))
  bad = sum(n for s, n in counts.items() if s not in ("equal", "compile-error"))
  return 0 if bad == 0 else 1


if __name__ == "__main__":
  sys.exit(main())
