"""Runs the structural verifier (toit_spec_verify) on every test program of
the suite compiled in format 2 (run_suite.py's program discovery) and on the
spec test programs in tests/toit.

Usage: verify_suite.py [--jobs N] [--filter SUBSTRING] [--out DIR] [--results FILE]
"""

import argparse
import concurrent.futures
import glob
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import run_suite  # noqa: E402

CRATE = run_suite.CRATE
REPO = run_suite.REPO
VERIFY = os.path.join(CRATE, "target/release/toit_spec_verify")


def compile_and_dump(src, out, dumper):
  name = os.path.relpath(src, REPO).replace("/", "_")[:-5]
  snapshot = os.path.join(out, name + ".snapshot")
  dump = os.path.join(out, name + ".dump")
  if not os.path.exists(dump):
    rc, _, err = run_suite.run([run_suite.TOIT_COMPILE, "-Xbytecode_format=2", "-w", snapshot, src], 300)
    if rc != 0:
      return None, "compile-error"
    rc, _, err = run_suite.run([run_suite.TOIT, "run", dumper, "--", snapshot, dump], 300)
    if rc != 0:
      return None, "dump-error"
  return dump, None


def one(src, opts):
  dump, err = compile_and_dump(src, opts.out, opts.dumper)
  if dump is None:
    return (src, err, "")
  p = subprocess.run([VERIFY, "--quiet", "--time", dump], capture_output=True)
  text = p.stdout.decode("utf-8", "replace")
  status = "accepted" if p.returncode == 0 else ("rejected" if p.returncode == 1 else "load-error")
  return (src, status, text)


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--jobs", type=int, default=os.cpu_count())
  ap.add_argument("--filter", action="append")
  ap.add_argument("--out", default=os.path.join(CRATE, "target/verify-suite"))
  ap.add_argument("--results", help="write one line per program: status program")
  opts = ap.parse_args()
  os.makedirs(opts.out, exist_ok=True)
  subprocess.run(["cargo", "build", "--release", "--quiet", "--bin", "toit_spec_verify"], cwd=CRATE, check=True)
  opts.dumper = os.path.join(opts.out, "spec_dump.snapshot")
  if not os.path.exists(opts.dumper):
    subprocess.run([run_suite.TOIT, "compile", "--snapshot", "-o", opts.dumper,
                    os.path.join(REPO, "tools/spec_dump.toit")], check=True)
  files = [os.path.join(REPO, f) for f in run_suite.discover(opts.filter)]
  files += sorted(glob.glob(os.path.join(CRATE, "tests/toit/*.toit")))
  if opts.filter:
    files = [f for f in files if any(x in f for x in opts.filter)]
  results = []
  with concurrent.futures.ThreadPoolExecutor(max_workers=opts.jobs) as ex:
    for r in ex.map(lambda f: one(f, opts), files):
      results.append(r)
      if r[1] != "accepted":
        print("%s %s" % (r[1], os.path.relpath(r[0], REPO)))
        for line in r[2].splitlines()[1:6]:
          print("    " + line)
  counts = {}
  for _, status, _ in results:
    counts[status] = counts.get(status, 0) + 1
  print("programs: %d; %s" % (len(results), ", ".join("%s %d" % kv for kv in sorted(counts.items()))))
  if opts.results:
    with open(opts.results, "w") as f:
      f.write("# Generated by tests/verify_suite.py: status, program.\n")
      for src, status, _ in sorted(results):
        f.write("%s %s\n" % (status, os.path.relpath(src, REPO)))
  return 0 if counts.get("rejected", 0) == 0 else 1


if __name__ == "__main__":
  sys.exit(main())
