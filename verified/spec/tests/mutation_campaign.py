"""Mutation campaign of the structural verifier (Phase 3 exit criterion).

Runs toit_spec_mutate on the format-2 dumps of the spec test programs and of
the suite tests that pass on the reference interpreter in format 2
(tests/suite-status.txt), in parallel, and adds up the results. The dumps
come from verify_suite.py (run it first).

Usage: mutation_campaign.py [--count N] [--jobs N] [--max-steps M] [--seed S] [--out FILE]
"""

import argparse
import collections
import glob
import os
import re
import subprocess
import sys
import concurrent.futures

CRATE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MUTATE = os.path.join(CRATE, "target/release/toit_spec_mutate")
DUMPS = os.path.join(CRATE, "target/verify-suite")


def programs(limit):
  dumps = sorted(glob.glob(os.path.join(DUMPS, "verified_spec_tests_toit_*.dump")))
  with open(os.path.join(CRATE, "tests/suite-status.txt")) as f:
    for line in f:
      parts = line.split()
      if len(parts) >= 3 and parts[0] == "2" and parts[1] == "pass":
        d = os.path.join(DUMPS, parts[2].replace("/", "_")[:-5] + ".dump")
        if os.path.exists(d):
          dumps.append(d)
  return dumps[:limit]


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--count", type=int, default=12000)
  ap.add_argument("--jobs", type=int, default=os.cpu_count())
  ap.add_argument("--max-steps", type=int, default=100000)
  ap.add_argument("--seed", type=int, default=1)
  ap.add_argument("--programs", type=int, default=60)
  ap.add_argument("--out", default=os.path.join(CRATE, "tests/mutation-results.txt"))
  opts = ap.parse_args()
  subprocess.run(["cargo", "build", "--release", "--quiet", "--bin", "toit_spec_mutate"], cwd=CRATE, check=True)
  dumps = programs(opts.programs)
  per = max(1, opts.count // len(dumps))
  def one(i):
    d = dumps[i]
    p = subprocess.run([MUTATE, "--count", str(per), "--seed", str(opts.seed + i),
                        "--max-steps", str(opts.max_steps), d], capture_output=True)
    return d, p.stdout.decode("utf-8", "replace")
  totals = collections.Counter()
  ends = collections.Counter()
  findings = []
  with concurrent.futures.ThreadPoolExecutor(max_workers=opts.jobs) as ex:
    for d, out in ex.map(one, range(len(dumps))):
      section = None
      for line in out.splitlines():
        m = re.match(r"^  ([^:]+): (\d+)$", line)
        m2 = re.match(r"^    ([^:]+): (\d+)$", line)
        if line.startswith("  accepted mutants by"):
          section = "ends"
        elif line.startswith("  soundness findings"):
          section = "findings"
        elif section == "findings" and line.startswith("    "):
          findings.append(line.strip())
        elif section == "ends" and m2:
          ends[m2.group(1)] += int(m2.group(2))
        elif m and section is None:
          totals[m.group(1)] += int(m.group(2))
  mutants = sum(v for k, v in totals.items() if k.endswith("mutants"))
  lines = []
  lines.append("# Generated by tests/mutation_campaign.py (seed %d, %d programs, max %d steps per run)."
               % (opts.seed, len(dumps), opts.max_steps))
  lines.append("mutants: %d" % mutants)
  for k in sorted(totals):
    lines.append("  %s: %d" % (k, totals[k]))
  lines.append("accepted mutants by how the run ended:")
  for k in sorted(ends):
    lines.append("  %s: %d" % (k, ends[k]))
  lines.append("soundness findings (accepted and stuck or interpreter panic): %d" % len(findings))
  for f in findings:
    lines.append("  " + f)
  lines.append("programs:")
  for d in dumps:
    lines.append("  " + os.path.basename(d))
  text = "\n".join(lines) + "\n"
  print(text)
  with open(opts.out, "w") as f:
    f.write(text)
  return 0 if not findings else 1


if __name__ == "__main__":
  sys.exit(main())
