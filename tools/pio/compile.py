"""Compile standard .pio assembly into a Toit module using Pico SDK pioasm."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys


def constant(name):
    name = name.replace("_", "-").upper()
    if not re.fullmatch(r"[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)*", name):
        raise ValueError(f"Cannot export PIO name as a Toit constant: {name!r}")
    return name


def generate(document):
    lines = ["// Copyright (C) 2026 Toit contributors.",
             "// Use of this source code is governed by an MIT-style license in lib/LICENSE.",
             "// Generated by tools/pio/compile.py. Edit the .pio source instead.",
             "", "import rp2350.pio", ""]
    names = set()

    def export(name, expression):
        if name in names:
            raise ValueError(f"Duplicate generated name: {name}")
        names.add(name)
        lines.append(f"{name} ::= {expression}")

    for name, value in document["publicSymbols"].items():
        export(constant(name), str(value))
    for program in document["programs"]:
        prefix = constant(program["name"])
        export(prefix + "-PROGRAM", "pio.Program [")
        for instruction in program["instructions"]:
            lines.append(f"  0x{instruction['hex'].lower()},  // {instruction['instruction']}")
        lines.append("]")
        options = {
            "origin": program["origin"], "pio-version": program["pioVersion"],
            "used-gpio-ranges": program["usedGPIORanges"],
            "wrap-target": program["wrapTarget"], "wrap": program["wrap"],
        }
        for direction, auto, threshold in [("in", "push", "autopush"), ("out", "pull", "autopull")]:
            settings = program[direction]
            if settings:
                options[direction + "-count"] = settings["pinCount"]
                options[direction + "-shift"] = "pio.SHIFT-RIGHT" if settings["right"] else "pio.SHIFT-LEFT"
                options["auto-" + auto] = settings[threshold]
                options[auto + "-threshold"] = settings["threshold"]
        if program["setCount"] is not None:
            options["set-count"] = program["setCount"]
        if program["sideset"]:
            side = program["sideset"]
            options.update({"side-count": side["size"] - int(side["optional"]),
                            "side-optional": side["optional"], "side-pindirs": side["pindirs"]})
        if program["fifoConfig"]:
            options["fifo"] = {"PIO_FIFO_JOIN_TX": 1, "PIO_FIFO_JOIN_RX": 2,
                               "PIO_FIFO_JOIN_TXGET": 4, "PIO_FIFO_JOIN_TXPUT": 8,
                               "PIO_FIFO_JOIN_PUTGET": 12}[program["fifoConfig"]]
        if program["clockDiv"]:
            divider = program["clockDiv"]
            options["clock-divider"] = (divider["int"] or 65536) + divider["frac"] / 256
        if program["movStatus"]:
            status = program["movStatus"]
            options["mov-status"] = {"STATUS_TX_LESSTHAN": 0, "STATUS_RX_LESSTHAN": 1,
                                     "STATUS_IRQ_SET": 2}[status["type"]]
            options["mov-status-n"] = status["n"]
        for key, value in options.items():
            if isinstance(value, bool):
                lines.append("    --" + ("" if value else "no-") + key)
            else:
                lines.append(f"    --{key}={value}")
        for key in ("publicSymbols", "publicLabels"):
            for name, value in program[key].items():
                export(prefix + "-" + constant(name), str(value))
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("-o", "--output", required=True, type=Path)
    parser.add_argument("--pioasm", default="pioasm")
    args = parser.parse_args()
    result = subprocess.run([args.pioasm, "-o", "json", str(args.source)],
                            capture_output=True, text=True)
    if result.stderr:
        sys.stderr.write(result.stderr)
    if result.returncode:
        raise SystemExit(result.returncode)
    generated = generate(json.loads(result.stdout))
    args.output.write_text(generated)


if __name__ == "__main__":
    main()
