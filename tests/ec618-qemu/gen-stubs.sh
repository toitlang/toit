# Writes the stubs of the QEMU harness (CMakeLists.txt): one definition for
# every symbol the probe link left undefined (the EC618 base's functions and
# data the linked VM objects reference). A symbol the base defines as data
# becomes zeroed data of the base's size; any other becomes a function that
# reports its name and stops the run (exit code 73).
#
# Usage: gen-stubs.sh NM PROBE-ELF BASE-ELF OUT

set -eu
NM="$1"
PROBE="$2"
BASE="$3"
OUT="$4"

"$NM" -S "$BASE" > "$OUT.base"
"$NM" -u "$PROBE" | awk '$1 == "U" { print $2 }' | sort -u > "$OUT.undefined"

{
  echo "// Generated by tests/ec618-qemu/gen-stubs.sh from $(basename "$PROBE"); do not edit."
  echo "void harness_puts(const char* s);"
  echo "__attribute__((noreturn)) void harness_exit(int code);"
  echo "__attribute__((noreturn)) static void unimplemented(const char* name) {"
  echo "  harness_puts(\"\\n[harness] the run reached a stub of the EC618 base: \");"
  echo "  harness_puts(name);"
  echo "  harness_puts(\"\\n\");"
  echo "  harness_exit(73);"
  echo "}"
  awk '
    function hex(s,   v, k) {
      v = 0
      for (k = 1; k <= length(s); k++) v = v * 16 + index("0123456789abcdef", tolower(substr(s, k, 1))) - 1
      return v
    }
    NR == FNR {
      # Lines: ADDRESS [SIZE] TYPE NAME.
      if (NF == 4) { type[$4] = $3; size[$4] = hex($2) }
      else if (NF == 3) { type[$3] = $2 }
      next
    }
    {
      name = $1; t = type[name]; i++
      if (t ~ /^[DdBbRrGgSsC]$/) {
        n = size[name] > 0 ? size[name] : 4
        printf "char harness_data_%d[%d] __asm__(\"%s\") __attribute__((aligned(8)));\n", i, n, name
      } else {
        printf "void harness_stub_%d(void) __asm__(\"%s\");\n", i, name
        printf "void harness_stub_%d(void) { unimplemented(\"%s\"); }\n", i, name
      }
    }' "$OUT.base" "$OUT.undefined"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "gen-stubs.sh: $(wc -l < "$OUT.undefined") stubs" >&2
