// The EC618 VM library (libtoit_vm.a, the Rust core, mbedTLS: the objects
// of the slot link) on QEMU's mps2-an385, a generic Cortex-M3 board, with
// the EC618 base's prebuilt FreeRTOS kernel and its heap (cmpctmalloc).
//
// The harness replaces what needs the EC618's peripherals: it defines the
// symbols of a few VM objects itself (the platform event sources, the flash
// registry, now in RAM), so that the linker does not take those objects from
// the archive, and the base functions the VM and the kernel call (clock,
// trace and sleep hooks, the TRNG). Every other base function the linked
// objects reference is a stub that stops the run (stubs.c, generated by
// gen-stubs.sh); programs that need no peripherals never reach one.
//
// The images come from extension.toit, which QEMU loads to the PSRAM
// (EXTENSION_HEADER): the first one boots, as on the device (toit_ec618.cc,
// start). The program's output goes to the semihosting console; the exit
// code of QEMU is the VM's exit reason (0: done).

